-- 0042_overtime_leave_deductions.sql
--
-- 补钟用存假抵扣（2026-10-31 用户裁定，见 `docs/adr/0124`）：员工把**自己攒的存假**
-- 折成天数抵掉当月欠的补钟 —— 存假减 X 天、对应补钟小时从「净时长」里注销，那部分
-- 时间按休假算、不再欠班。它是 `overtime_entries`（补钟台账）与 `attendance_ledger`
-- （存假台账）之间的那张桥：**只记「员工 × 归月 × 天数」的月度汇总**，不追溯到
-- 具体哪几笔补钟（整天粒度本来就不对齐单笔：8.5 小时 = 1 天，一笔可能是 6 小时）。
--
-- 三条口径刻在这张表的形状上：
--
-- * **归月 = 补钟登记月**（`month` 是 `YYYY-MM` 的自然月，与 `overtime_entries.entry_date`
--   的归月同一条）。10/31 登记、11/1 申请也行（10 月还没封账），但叩的是 10 月的账。
-- * **只能整天**：`days` 是正整数，`half_hours = days × 17`（8.5 小时 = 17 个半小时，
--   与加班费公式的分母 `HOURS_PER_DAY` 同源）。CHECK 把这条一致性钉在库里，服务层
--   算错一次就会被数据库拒掉。
-- * **状态机与加班登记完全同一套**（`pending` / `approved` / `rejected` / `cancelled` /
--   `voided`，见 `services/overtime/ledger.py` 的 `STATUS_*`）：员工提、店长批、员工可撤
--   未批的、驳回必写理由、批准后只有超管能在**封账前**作废。作废不是删除 —— 那一行
--   留着（`voided`），月底对账时要说得清「曾经抵过、又被撤回了」。
--
-- 幂等：`IF NOT EXISTS`，可重复执行。这是**加成性**变更（建新表），符合 README 的规矩。
-- 写入只有 `services/overtime/ledger.py` 一个口；本表与 OVERTIME_TABLES 同组，数据浏览器
-- 只读列出。

CREATE TABLE IF NOT EXISTS overtime_leave_deductions (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "employee_id" BIGINT NOT NULL,
    "month" TEXT NOT NULL,
    "days" INTEGER NOT NULL,
    "half_hours" INTEGER NOT NULL,
    "status" TEXT NOT NULL,
    "created_by" TEXT NOT NULL,
    "decided_by" TEXT,
    "decided_at" TEXT,
    "reject_reason" TEXT,
    "created_at" TEXT NOT NULL,
    "updated_at" TEXT NOT NULL,
    -- 只能整天：0 天与负数都不是「抵扣」，是脏数据。
    CONSTRAINT overtime_leave_deductions_days_positive CHECK ("days" >= 1),
    -- 天数与半小时数必须自洽（17 个半小时 = 8.5 小时 = 1 天）。服务层只管算，
    -- 这条 CHECK 管它算错时不会静默落库。
    CONSTRAINT overtime_leave_deductions_half_hours_match
        CHECK ("half_hours" = "days" * 17),
    -- 状态取值与 `overtime_entries` 同一份契约；多一个字就是第二套状态机。
    CONSTRAINT overtime_leave_deductions_status_check
        CHECK ("status" IN ('pending', 'approved', 'rejected', 'cancelled', 'voided'))
);

-- 读口的三条路都走（员工, 月）：员工端「我提过哪些」、审批队列、以及考勤表/净时长
-- 按「员工 × 归月」汇总已批准天数。前导带 `tenant_id` 的理由同 0026 / 0027。
CREATE INDEX IF NOT EXISTS idx_overtime_leave_deductions_employee_month
    ON overtime_leave_deductions (tenant_id, "employee_id", "month", "status");

-- 审批队列与全店统计按「月 + 状态」扫（待批那一队旧的在前）。
CREATE INDEX IF NOT EXISTS idx_overtime_leave_deductions_month_status
    ON overtime_leave_deductions (tenant_id, "month", "status", "created_at");
