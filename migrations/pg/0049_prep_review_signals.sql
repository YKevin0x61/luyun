-- 0046_prep_review_signals.sql
--
-- 备货复盘信号（票 01 / `.scratch/prep-review/spec.md` §3、§4）。
--
-- 现状：复盘只回答「那天够不够卖」（够卖率 / 缺货量 / 多出量 / 参考÷实际），因为
-- 采集侧只留了整点的小时快照。要回答「准不准、为什么不准、多备少备的代价、执行到
-- 不到位」，就得把**现场事件**、**销量轨迹**与**环境信号**一起留下来。
--
-- 三样东西为什么是这三种形状：
--
--   · `prep_plan_events`（事件流，一张新表）—— 手改 / 点完成 / 首次售罄 / 窗口结束
--     是**时点事件**，一天多条、与小时快照不对齐。塞进按小时一行的快照表会变成
--     「同一列在不同行里表达不同含义」，所以单独一张表。`at` 是 ISO8601（+08:00），
--     `plan_day` 是自然日 `YYYY-MM-DD`（与 `prep_plan_days` 同口径，不是 06:00 切的
--     营业日）；`kind` 取 `manual_edit` / `done` / `sold_out` / `window_end`。
--     `qty_before` / `qty_after` 只在现场动作里出现（手改的前后值、完成时的建议量），
--     其余事件留空；`meta_json` 收各 kind 自己的补充字段，避免为每种事件加列。
--     `prep_item_id` 可空：窗口级事件（`window_end`）不对应某一个品，历史回填不编造
--     事件时也会留空。索引按「一天 × 一个品 × 时间顺序」建 —— 复盘页就是这么读的。
--
--   · `prep_plan_context`（环境信号，一天一行）—— 节假日 / 天气 / 当天档口上班人数 /
--     店长备注是**当天整天的快照**，不是每小时一个值。冗余存一份而不是每次去关联
--     `statutory_holidays` 或现查排班：外部表后来改了（补录节假日、调整班次），不能
--     让历史复盘结论跟着变。唯一键把「一天一行」交给库这一层，写入按天 upsert。
--     `weather_json` / `staff_json` 是 JSON 文本（同仓库既有口径，`TEXT` 而不是
--     `JSONB`），形状见 spec §4 注释。
--
--   · `prep_plan_actuals` 加列（销量轨迹）—— 窗口结束后在**固定时点**补采：窗口后
--     1h / 2h、次日同钟点，以及堂食 / 外卖 / 退菜拆分与逐小时曲线。固定三个时点用
--     **列**而不是行：与既有 actuals 的「一行 = 一个窗口 × 一个品」对齐，复盘一次
--     读出整行；`hourly_json` 收没法预先定列的逐小时曲线。全部可空（历史窗口回填
--     不到就留 null），`hourly_json` 带默认 `'[]'` 让读取端不用判空。
--
--   · `wastage_records` 加列（损耗对齐）—— 复盘要把报废量和备货建议对上，才能算
--     「多备少备的代价」。登记时可选地挂到某个备货品（`prep_item_id` 可空，为空时
--     复盘用品名兜底），`window_start` / `window_end` 把一笔报废落进某个窗口。
--     加列可空，既有登记行与应用前完全一样。
--
-- 幂等：建表 / 建索引 / 加列全部 `IF NOT EXISTS`，可重复执行。纯加成性变更：不动既有
-- 列类型、不删列、不删行。schema 不随启动生效，需在 Admin「系统更新 → 数据库迁移」
-- 或更新作业的 `applying_migrations` 阶段应用（见 `migrations/pg/README.md`）。

CREATE TABLE IF NOT EXISTS "prep_plan_events" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "tenant_id" BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    -- ISO8601 带 +08:00 偏移；仓库里时间戳一律 TEXT（见 README「已知取舍」）。
    "at" TEXT NOT NULL,
    -- 自然日 YYYY-MM-DD，与 prep_plan_days 同口径。
    "plan_day" TEXT NOT NULL,
    "prep_item_id" BIGINT,
    "kind" TEXT NOT NULL,
    "qty_before" DOUBLE PRECISION,
    "qty_after" DOUBLE PRECISION,
    "employee_id" BIGINT,
    "station" TEXT,
    "meta_json" TEXT NOT NULL DEFAULT '{}'
);

-- 复盘页按「某天 → 某个品 → 时间顺序」读事件；窗口级事件按天读（prep_item_id 为空）。
CREATE INDEX IF NOT EXISTS "idx_prep_events_day_item"
    ON "prep_plan_events" ("plan_day", "prep_item_id", "at");

CREATE TABLE IF NOT EXISTS "prep_plan_context" (
    -- 通用后台表格页按 `rowid`（方言层改写为 `id`）定位行，缺 id 会让
    -- `/api/admin/tables/prep_plan_context/rows` 500、行编辑/删除一起坏，
    -- 所以这张「一天一行」的表也带一个代理主键，业务唯一性仍由下面的 UNIQUE 保证。
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "tenant_id" BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "plan_day" TEXT NOT NULL,
    -- 当天法定节假日名（statutory_holidays.name 的快照）；平日为空。
    "holiday_name" TEXT,
    -- 天气快照：{text, temp_max, temp_min, precip, source, fetched_at}。
    "weather_json" TEXT NOT NULL DEFAULT '{}',
    -- 当天档口上班人数：{"熟笼": 3, "案板": 2, ...}。
    "staff_json" TEXT NOT NULL DEFAULT '{}',
    -- 店长每日特殊备注（团餐 / 活动 / 停水 / 设备故障）。
    "note" TEXT,
    "captured_at" TEXT NOT NULL,
    "updated_at" TEXT NOT NULL,
    -- 「一天一行」由库保证；写入按 (tenant_id, plan_day) upsert。
    UNIQUE ("tenant_id", "plan_day")
);

-- 实际侧补列：固定时点的销量轨迹与渠道拆分（可空 —— 历史窗口回填不到就留 null）。
ALTER TABLE "prep_plan_actuals" ADD COLUMN IF NOT EXISTS "sold_1h" DOUBLE PRECISION;
ALTER TABLE "prep_plan_actuals" ADD COLUMN IF NOT EXISTS "sold_2h" DOUBLE PRECISION;
ALTER TABLE "prep_plan_actuals" ADD COLUMN IF NOT EXISTS "sold_next_day" DOUBLE PRECISION;
ALTER TABLE "prep_plan_actuals" ADD COLUMN IF NOT EXISTS "dine_in_qty" DOUBLE PRECISION;
ALTER TABLE "prep_plan_actuals" ADD COLUMN IF NOT EXISTS "delivery_qty" DOUBLE PRECISION;
ALTER TABLE "prep_plan_actuals" ADD COLUMN IF NOT EXISTS "refund_qty" DOUBLE PRECISION;
-- 逐小时销量曲线 [{"hour": "07:00", "qty": 12}, ...]。
ALTER TABLE "prep_plan_actuals" ADD COLUMN IF NOT EXISTS "hourly_json" TEXT NOT NULL DEFAULT '[]';

-- 损耗对齐到备货品（可空；为空时复盘用品名兜底）。
ALTER TABLE "wastage_records" ADD COLUMN IF NOT EXISTS "prep_item_id" BIGINT;
ALTER TABLE "wastage_records" ADD COLUMN IF NOT EXISTS "window_start" TEXT;
ALTER TABLE "wastage_records" ADD COLUMN IF NOT EXISTS "window_end" TEXT;
