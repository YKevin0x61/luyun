-- 0026_statutory_holidays.sql
--
-- 法定节假日日历（考勤面，票 02）：超级管理员在管理端逐日标记「这天是法定节假日」，
-- 并写一个名称（国庆、春节）。**只标法定节假日，不标调休上班日** —— 补休规则只用得到
-- 前者（`GLOSSARY.md` 的「法定节假日日历」）。
--
-- 为什么必须有这张表：`docs/adr/0113` 的「法定节假日补休」= 当月每个法定节假日、那天
-- 排了班的员工多得 1 天假。哪几天算法定节假日**只有这一份依据** —— 代码里不写死一张
-- 年度表（写死的表每年要人改代码，而且改的是代码不是数据；`GLOSSARY.md` 的 _Avoid_
-- 点名了这条）。2026-10 上线当月的补休也认这张日历。
--
-- 一条记录 = 一个自然日 + 名称。**日期唯一**：同一天重复标记是覆盖那一行（写路径用
-- `ON CONFLICT (tenant_id, day) DO UPDATE`），不是新增第二行。`day` 是 `YYYY-MM-DD`
-- 的自然日字符串 —— 沿用仓库口径：业务表的日期都是 TEXT，不是 date 类型。
--
-- 录入方式：管理端「节假日日历」页（`/workbench/hr/holidays`，写入口在
-- `api/attendance_holidays.py`）。本表在 `db_core.schema.ATTENDANCE_TABLES` 里，因此
-- 进 `ADMIN_READ_ONLY_TABLES`：数据浏览器只读列出，没有通用写入口 —— 同 SCHEDULING /
-- OVERTIME 那几组表的理由。
--
-- 幂等：IF NOT EXISTS，可重复执行。这是**加成性**变更（建新表），符合 README 的规矩。

CREATE TABLE IF NOT EXISTS statutory_holidays (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "day" TEXT NOT NULL,
    "name" TEXT NOT NULL,
    "created_at" TEXT NOT NULL,
    "updated_at" TEXT NOT NULL
);

-- 日期唯一。**行标识列（`id`）另给**，不拿 `day` 当主键：admin 的行定位靠
-- `rowid`（方言层把它改写成这张表的 `id`），主键换名字那一层就得跟着特判；其余业务表
-- 也一律是「代理主键 + 业务键唯一索引」。
-- 前导列带 `tenant_id` 的理由同 0025：唯一约束要正好覆盖 upsert 的冲突目标
-- （`ON CONFLICT (tenant_id, day)`）。单店阶段的代码里没有租户条件，写默认值 1。
CREATE UNIQUE INDEX IF NOT EXISTS idx_statutory_holidays_day
    ON statutory_holidays (tenant_id, "day");
