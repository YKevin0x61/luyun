-- 0054：工作台「任务」域 —— 即时任务 / 定期任务 / 期实例 / 提交 / 照片
--
-- 背景：工作台此前只有三套各管一段的待办（排班申请、加班补钟、卫生验收），
-- 没有「临时派一件活、到点前拍照交、店长验收」这种通用任务。这一组表就是那件事
-- 的数据面（设计见 docs/adr/0131-work-tasks-independent-domain.md、
-- 0132-task-assignment-people-and-pools.md、0133-recurring-task-definition-and-instances.md）。
--
-- 两条主线：
--   · 定义（definition）= 这件活是什么、派给谁、什么时候要、要几张照片。即时任务只
--     生成一次，定期任务按频率在**工作台日**（自然日 00:00 切）上反复出现。
--   · 实例（instance）= 某一期真实要做的活。定义一旦发布，后续改动只影响**还没生成**
--     的期；已生成的实例保留当时的内容快照（标题 / 说明 / 照片张数 / 截止时刻 / 指派），
--     否则店长改了明天的措辞，昨天那期的验收记录会跟着变。
--
-- 为什么定义与实例是两张表、为什么即时任务也走实例：即时任务是「只生成一次的定义」，
-- 两者共用同一套状态机、提交与验收路径；分开建模会让 90% 的代码写两遍（ADR 0133）。
--
-- 指派口径（ADR 0132）：`assignee_kind` 只有两种 ——
--   group：`work_task_definition_members` 里 1..N 个具名真人，合成**一份**任务，
--          谁先交算谁完成（不是按人拆份）；
--   pool ：按规则在**实例那一期**解析出可做的人（全体在职 / 有管理能力的员工 /
--          当天当班 / 当天在某卫生工作区当班）。池任务不认领、先交为准。
-- 实例上的三个指派列是**快照**：组任务把成员名抄进 instance_members；池任务只存
-- pool_kind 与 pool_zone_id，成员在提交/展示时按 period_date 的排班现算。
--
-- 照片（同 0029 损耗的口径）：字节走 FileCaptureStore 落盘（独立目录
-- `task-captures`），库里只存 capture_id 与元数据。上传与提交是**两步**：先传图拿
-- capture_id（`work_task_images`），提交时再带 id 绑到 `work_task_submission_photos`。
-- 因此 `work_task_images` 允许「传了但没提交成功」的孤儿行，供以后按 `created_at` 清。
-- 参考图与完成照共用这张台账，用 `purpose` 区分 —— 提交时校验 capture_id 必须是
-- **提交人自己**传的 submission 图，防拿参考图当完成照。
--
-- 幂等：全是新表 + IF NOT EXISTS，可重复执行；既有表与查询在应用前后一个字都不变。
-- 应用不在启动期建结构，本文件要提交进发行包、由门店在「系统更新 → 数据库迁移」应用。

CREATE TABLE IF NOT EXISTS work_task_definitions (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- once = 即时任务（发布即生成一期）；recurring = 定期任务。
    "kind" TEXT NOT NULL,
    "title" TEXT NOT NULL,
    "body" TEXT NOT NULL DEFAULT '',
    -- 本期要交几张完成照，1~3（发布表单选择，默认 1）。
    "photo_count" INTEGER NOT NULL DEFAULT 1,
    -- 参考图：可选一张，「先看参考图 → 开相机」两步拍照里那一张。
    "reference_capture_id" TEXT,
    -- 指派：group（具名小组）或 pool（规则池）；池再细分四种。
    "assignee_kind" TEXT NOT NULL,
    "pool_kind" TEXT,
    "pool_zone_id" BIGINT,
    -- 每期的截止时刻（HH:mm，工作台日当天）；一期在 period_date 那天到期。
    "deadline_hhmm" TEXT NOT NULL,
    -- 即时任务：应完成的工作台日（也是它唯一一期的 period_date）。
    "due_date" TEXT,
    -- 定期任务：频率与起止。weekday 0=周一 .. 6=周日（与 hygiene_deep_clean_items 同）；
    -- month_day 1..31，某月没有这一天就跳过那一期（不提前、不推后）。
    "frequency_kind" TEXT,
    "weekday" INTEGER,
    "month_day" INTEGER,
    "start_date" TEXT,
    "end_date" TEXT,
    -- active / stopped。停用只影响以后不再生成新期，历史实例保留。
    "status" TEXT NOT NULL DEFAULT 'active',
    -- 发布时是否顺手把这个任务发到企微群（默认不发；ADR 0131 决定 7）。
    "wecom_group_push" INTEGER NOT NULL DEFAULT 0,
    -- 发布人快照：管理端共享账号没有员工号；员工端发布记员工号与姓名。
    "created_by_kind" TEXT NOT NULL,
    "created_by_employee_id" BIGINT,
    "created_by_name" TEXT NOT NULL,
    "created_at" TEXT NOT NULL,
    "updated_at" TEXT NOT NULL,
    CONSTRAINT work_task_definitions_kind_known
        CHECK ("kind" IN ('once', 'recurring')),
    CONSTRAINT work_task_definitions_title_not_blank
        CHECK (length(btrim("title")) > 0),
    CONSTRAINT work_task_definitions_photo_count_range
        CHECK ("photo_count" BETWEEN 1 AND 3),
    CONSTRAINT work_task_definitions_deadline_hhmm_format
        CHECK ("deadline_hhmm" ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
    CONSTRAINT work_task_definitions_assignee_known
        CHECK (
            (assignee_kind = 'group'
                AND pool_kind IS NULL AND pool_zone_id IS NULL)
            OR (assignee_kind = 'pool'
                AND pool_kind IN ('all_staff', 'managers', 'on_duty', 'zone_on_duty')
                AND (pool_kind = 'zone_on_duty') = (pool_zone_id IS NOT NULL))
        ),
    CONSTRAINT work_task_definitions_status_known
        CHECK ("status" IN ('active', 'stopped', 'cancelled')),  -- 即时任务撤回后置 cancelled，历史仍可查
    CONSTRAINT work_task_definitions_wecom_push_bool
        CHECK (wecom_group_push IN (0, 1)),
    CONSTRAINT work_task_definitions_creator_known
        CHECK (
            (created_by_kind = 'admin' AND created_by_employee_id IS NULL)
            OR (created_by_kind = 'staff' AND created_by_employee_id IS NOT NULL)
        ),
    CONSTRAINT work_task_definitions_kind_fields
        CHECK (
            ("kind" = 'once'
                AND due_date IS NOT NULL
                AND frequency_kind IS NULL
                AND weekday IS NULL
                AND month_day IS NULL
                AND start_date IS NULL
                AND end_date IS NULL)
            OR ("kind" = 'recurring'
                AND due_date IS NULL
                AND frequency_kind IN ('daily', 'weekly', 'monthly')
                AND start_date IS NOT NULL
                AND (end_date IS NULL OR end_date >= start_date)
                AND (
                    (frequency_kind = 'daily'
                        AND weekday IS NULL AND month_day IS NULL)
                    OR (frequency_kind = 'weekly'
                        AND weekday BETWEEN 0 AND 6 AND month_day IS NULL)
                    OR (frequency_kind = 'monthly'
                        AND month_day BETWEEN 1 AND 31 AND weekday IS NULL)
                ))
        )
);

-- 定期任务每天被物化循环扫一遍：按状态与种类找活的定义。
CREATE INDEX IF NOT EXISTS idx_work_task_definitions_status
    ON work_task_definitions (status, "kind");

-- 「我的任务」与首页角标按创建人读。
CREATE INDEX IF NOT EXISTS idx_work_task_definitions_creator
    ON work_task_definitions (created_by_kind, created_by_employee_id, created_at);

CREATE TABLE IF NOT EXISTS work_task_definition_members (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "definition_id" BIGINT NOT NULL REFERENCES work_task_definitions(id) ON DELETE CASCADE,
    "employee_id" BIGINT NOT NULL,
    -- 姓名快照：花名册改名或员工离职后，历史任务仍按当时的写法显示。
    "employee_name" TEXT NOT NULL,
    "sort_order" BIGINT NOT NULL DEFAULT 0,
    UNIQUE (tenant_id, definition_id, employee_id)
);

CREATE INDEX IF NOT EXISTS idx_work_task_definition_members_definition
    ON work_task_definition_members (definition_id, sort_order);

CREATE TABLE IF NOT EXISTS work_task_instances (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "definition_id" BIGINT NOT NULL REFERENCES work_task_definitions(id) ON DELETE CASCADE,
    -- 这一期属于哪个工作台日（TEXT 的 YYYY-MM-DD，与全仓库日期列同口径）。
    "period_date" TEXT NOT NULL,
    -- 以下七列是**发布/物化时**的快照，之后改定义不改已生成的期。
    "title" TEXT NOT NULL,
    "body" TEXT NOT NULL DEFAULT '',
    "photo_count" INTEGER NOT NULL,
    "reference_capture_id" TEXT,
    "assignee_kind" TEXT NOT NULL,
    "pool_kind" TEXT,
    "pool_zone_id" BIGINT,
    -- 截止时刻（带日期的 ISO 文本）：period_date + deadline_hhmm，读取时直接比。
    "deadline_at" TEXT NOT NULL,
    -- todo 待交 / pending 待验收 / passed 已通过 / cancelled 已撤回（只有即时任务能撤回）。
    "status" TEXT NOT NULL DEFAULT 'todo',
    -- 待验收的那条提交：验收通过或驳回后由服务层挪动/清空。
    "pending_submission_id" BIGINT,
    "created_at" TEXT NOT NULL,
    "updated_at" TEXT NOT NULL,
    -- 同一件活在同一期只能有一条实例：物化循环靠这条唯一键做幂等。
    UNIQUE (tenant_id, definition_id, period_date),
    CONSTRAINT work_task_instances_status_known
        CHECK ("status" IN ('todo', 'pending', 'passed', 'cancelled')),
    CONSTRAINT work_task_instances_photo_count_range
        CHECK ("photo_count" BETWEEN 1 AND 3),
    CONSTRAINT work_task_instances_assignee_known
        CHECK (
            (assignee_kind = 'group'
                AND pool_kind IS NULL AND pool_zone_id IS NULL)
            OR (assignee_kind = 'pool'
                AND pool_kind IN ('all_staff', 'managers', 'on_duty', 'zone_on_duty')
                AND (pool_kind = 'zone_on_duty') = (pool_zone_id IS NOT NULL))
        )
);

-- 管理端三段列表与逾期标红：按状态 + 截止时刻读。
CREATE INDEX IF NOT EXISTS idx_work_task_instances_status
    ON work_task_instances (status, deadline_at);

-- 「某天要做什么」与定期任务完成率：按工作台日读。
CREATE INDEX IF NOT EXISTS idx_work_task_instances_period
    ON work_task_instances (period_date, status);

-- 实例详情从定义回查（定义删除级联已在唯一键前导列，这里补一个纯定义索引给列表用）。
CREATE INDEX IF NOT EXISTS idx_work_task_instances_definition
    ON work_task_instances (definition_id, period_date);

CREATE TABLE IF NOT EXISTS work_task_instance_members (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "instance_id" BIGINT NOT NULL REFERENCES work_task_instances(id) ON DELETE CASCADE,
    "employee_id" BIGINT NOT NULL,
    "employee_name" TEXT NOT NULL,
    "sort_order" BIGINT NOT NULL DEFAULT 0,
    UNIQUE (tenant_id, instance_id, employee_id)
);

CREATE INDEX IF NOT EXISTS idx_work_task_instance_members_instance
    ON work_task_instance_members (instance_id, sort_order);

CREATE TABLE IF NOT EXISTS work_task_submissions (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "instance_id" BIGINT NOT NULL REFERENCES work_task_instances(id) ON DELETE CASCADE,
    -- 只有员工能提交（管理端共享账号只发布/验收，ADR 0132）。
    "submitter_kind" TEXT NOT NULL,
    "submitter_employee_id" BIGINT NOT NULL,
    "submitter_name" TEXT NOT NULL,
    "submitted_at" TEXT NOT NULL,
    -- 提交时已过 deadline_at = 1（逾期仍可补交，但标出来）。
    "late" INTEGER NOT NULL DEFAULT 0,
    -- pending 待验收 / passed 通过 / rejected 驳回（驳回后这条保留，重交是新的行）。
    "status" TEXT NOT NULL DEFAULT 'pending',
    "reviewed_by_kind" TEXT,
    "reviewed_by_employee_id" BIGINT,
    "reviewed_by_name" TEXT,
    "reviewed_at" TEXT,
    "reject_reason" TEXT NOT NULL DEFAULT '',
    CONSTRAINT work_task_submissions_submitter_known
        CHECK (submitter_kind = 'staff' AND submitter_employee_id IS NOT NULL),
    CONSTRAINT work_task_submissions_late_bool
        CHECK (late IN (0, 1)),
    CONSTRAINT work_task_submissions_status_known
        CHECK ("status" IN ('pending', 'passed', 'rejected')),
    CONSTRAINT work_task_submissions_reviewer_known
        CHECK (
            reviewed_by_kind IS NULL
            OR (reviewed_by_kind = 'admin' AND reviewed_by_employee_id IS NULL)
            OR (reviewed_by_kind = 'staff' AND reviewed_by_employee_id IS NOT NULL)
        ),
    CONSTRAINT work_task_submissions_reject_reason_required
        CHECK ("status" <> 'rejected' OR length(btrim(reject_reason)) > 0)
);

-- 实例详情展开提交历史（新→旧）。
CREATE INDEX IF NOT EXISTS idx_work_task_submissions_instance
    ON work_task_submissions (instance_id, "id");

-- 管理端待验收队列。
CREATE INDEX IF NOT EXISTS idx_work_task_submissions_status
    ON work_task_submissions (status, submitted_at);

CREATE TABLE IF NOT EXISTS work_task_submission_photos (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "submission_id" BIGINT NOT NULL REFERENCES work_task_submissions(id) ON DELETE CASCADE,
    -- 本次提交里的第几张（0 起，按提交顺序渲染）。
    "position" INTEGER NOT NULL,
    "capture_id" TEXT NOT NULL,
    "created_at" TEXT NOT NULL,
    -- 一张照片只能绑到一条提交上，重复提交同一张会被库挡住。
    UNIQUE (tenant_id, capture_id),
    UNIQUE (tenant_id, submission_id, "position")
);

CREATE INDEX IF NOT EXISTS idx_work_task_submission_photos_submission
    ON work_task_submission_photos (submission_id, "position");

-- 照片台账：上传即记一行，提交时再绑到 submission_photos。
-- purpose=submission 是完成照（必须现场拍，服务端校验 live 标记）；
-- purpose=reference 是发布任务时的参考图（允许从相册选）。
CREATE TABLE IF NOT EXISTS work_task_images (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "capture_id" TEXT NOT NULL,
    "purpose" TEXT NOT NULL,
    -- 上传人快照：管理端共享账号没有员工号；员工记员工号，owner_key 用于「未绑定的
    -- 图只有上传者能看」那一条。
    "owner_kind" TEXT NOT NULL,
    "owner_employee_id" BIGINT,
    "owner_key" TEXT NOT NULL,
    "content_type" TEXT NOT NULL,
    "byte_size" BIGINT NOT NULL,
    "created_at" TEXT NOT NULL,
    UNIQUE (tenant_id, capture_id),
    CONSTRAINT work_task_images_purpose_known
        CHECK ("purpose" IN ('submission', 'reference')),
    CONSTRAINT work_task_images_owner_known
        CHECK (
            (owner_kind = 'admin' AND owner_employee_id IS NULL)
            OR (owner_kind = 'staff' AND owner_employee_id IS NOT NULL)
        )
);

-- 未绑定图按上传人查（清理与「自己传的只有自己能看」）。
CREATE INDEX IF NOT EXISTS idx_work_task_images_owner
    ON work_task_images (owner_key, created_at);

-- 以后按保留期清理时按用途 + 时间扫。
CREATE INDEX IF NOT EXISTS idx_work_task_images_purpose
    ON work_task_images ("purpose", created_at);
