-- 0025_prep_closed_days.sql
--
-- 备货计划的「歇业日」日历：店自己知道哪天整天不做生意（春节、国庆前三天、临时休整）。
--
-- 为什么需要它：预测器对这类日子**一无所知**。实测（2026-10-14）拿真库跑出来的结果 ——
-- 国庆当天（10-01，库里整天没有一条订单）它给出「52 个品、建议量合计 1311」，
-- 其中金莎的信心还是 `high`；中秋（09-25，同样没营业）是 51 个品、合计 1355。
-- 师傅照做就是报废，24 小时保质期。
--
-- 一条记录 = 一个**营业日**（06:00 切）整天不做。它有两个作用：
--   1. 落在停业日里的时段切片**不进建议量**（也就不会算出"今天要做多少"）；
--   2. 这些日子从「完整营业日」样本里剔除，免得被当成正常样本。
--
-- 录入方式：管理后台「数据管理」页直接增删 —— 本表在 `ALL_TABLES` 里，管理页会自动列出。
-- 一年录几次（春节 / 国庆 / 临时歇业）就够，不需要日常维护。
--
-- 幂等：IF NOT EXISTS，可重复执行。这是**加成性**变更（建新表），符合 README 的规矩。

CREATE TABLE IF NOT EXISTS "prep_closed_days" (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "day" TEXT NOT NULL,
    "note" TEXT NOT NULL DEFAULT '',
    "created_at" TEXT NOT NULL,
    "updated_at" TEXT NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "idx_prep_closed_days_day"
    ON "prep_closed_days" ("tenant_id", "day");
