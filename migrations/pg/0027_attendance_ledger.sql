-- 0027_attendance_ledger.sql
--
-- 月度考勤台账（考勤面，票 03）：一个员工 × 一个**自然月**一行，存假期期初余额、
-- 封账后的本月结余（存假），以及四个系统推不出来的手填列（本月班次 / 是否住宿 /
-- 借调门店 / 是否离职）。见 `GLOSSARY.md` 的「月度考勤台账」与 `docs/adr/0113`。
--
-- 为什么必须有这张表：存假是**跨月滚动**的账 —— 本月池 = 实际出勤折出的月例休 +
-- 法定节假日补休 + 生日假 + 年假 + 上月存假。上个月的余额只由当时那一次结算决定，
-- 从排班结果与加班台账重算一遍历史只会得到另一个数（ADR 0113）。所以每月落一行
-- 结余快照，由超级管理员手动封账（票 04）定稿；**当月只算不落库**（票 03 的读路径
-- 不写这张表），页面上的当月一切数字都是暂算值。
--
-- 期初余额的用法（票 03 的读路径，`services/attendance/store.py`）：某月的「上月存假」
-- = **上一月已封账那一行的结余**；上一月还没有已封账的行时（上线当月 2026-10 就是
-- 这一种）退回读**本月这一行的期初余额** —— 那是人工录入一次的「上月末余额」
-- （ADR 0113 的 Consequences）。
--
-- 列名沿用仓库口径：日期 / 时刻一律 TEXT（ISO 字符串，带 +08:00），天数用
-- DOUBLE PRECISION（可带 .5、可为负 —— 负数是欠班，不是脏数据）。
-- `month` 是 `YYYY-MM` 的自然月字符串，不是营业日（营业日 06:00 切那条口径只属于
-- `staff_assignments.business_date`）。
--
-- 录入方式：封账与手填列分别是票 04 / 票 05 的事，这一票只建表 + 只读它。本表在
-- `db_core.schema.ATTENDANCE_TABLES` 里，因此进 `ADMIN_READ_ONLY_TABLES`：数据浏览器
-- 只读列出，没有通用写入口 —— 同 SCHEDULING / OVERTIME 那几组表的理由。
--
-- 幂等：IF NOT EXISTS，可重复执行。这是**加成性**变更（建新表），符合 README 的规矩。

CREATE TABLE IF NOT EXISTS attendance_ledger (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "employee_id" BIGINT NOT NULL,
    "month" TEXT NOT NULL,
    "opening_balance" DOUBLE PRECISION,
    "closing_balance" DOUBLE PRECISION,
    "shift_name" TEXT,
    "lodging" TEXT,
    "borrowed_store" TEXT,
    "resigned" TEXT,
    "sealed_at" TEXT,
    "created_at" TEXT NOT NULL,
    "updated_at" TEXT NOT NULL
);

-- 员工 × 自然月唯一：同一员工同一个月只能有一行（期初 / 结余 / 手填列都是这一行上的
-- 一份快照）。前导列带 `tenant_id` 的理由同 0026：唯一约束要正好覆盖 upsert 的冲突
-- 目标（`ON CONFLICT (tenant_id, employee_id, month)`）。单店阶段的代码里没有租户条件，
-- 写默认值 1。
CREATE UNIQUE INDEX IF NOT EXISTS idx_attendance_ledger_employee_month
    ON attendance_ledger (tenant_id, "employee_id", "month");
