-- 0056_refund_records.sql
--
-- 异常明细（商龙云移动报表「异常汇总」：退单 + 赠单）。
--
-- 背景：订单表里的退菜行是爬虫按「连续缺席 + 金额变小」差分推断出来的（见
-- scraper/table_change_detector.py），份数在软取消时被归零，原因与操作人也拿不到；
-- POS 自己回滚的隐藏退菜更是完全抓不到。cy7mm 的 exceptiondetail/getexceptionco
-- 直接给菜品级退单明细：份数、金额、原因、操作人、授权人、退菜时刻都有，是比差分
-- 更权威的一手数据。
--
-- 为什么不写回 orders：KDS 与备货都按 orders.status='退菜' 的实时口径工作，往
-- 里插第二来源会让同一笔退菜被两条链路各记一次，报表翻倍。所以只落这张独立表，
-- 报表另起一张明细表读它，orders 一个字不动。
--
-- 一行 = 一条退单 / 赠单明细（账单 children 里的一个菜品）。账单级字段（桌台、单号、
-- 结算人）在这行上冗余存一份：接口按账单分页返回，展示又按明细行平铺，冗余比
-- 两张表 join 省事得多，量级也小（一家店一天几十行）。
--
-- 幂等：新表 + IF NOT EXISTS；同步侧按 bs_id 整单删旧再插新（见
-- db_core/refund_records_repo.py 的 refund_records_replace_bill），
-- (tenant_id, shop_id, kind, bs_id, source_line) 再加唯一索引兜底。
--
-- 注意：这张表在门店是「先建表、后应用迁移」的，CREATE TABLE IF NOT EXISTS 会整段
-- 跳过，kind 列和两个索引都落不上（表现为 /api/analytics/refunds/detail 报
-- column "kind" does not exist）。补救见 0057_refund_records_kind.sql。

CREATE TABLE IF NOT EXISTS "refund_records" (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 门店 ID（credentials 里的 shop_id）。跨店部署时同一天的单号可能重号。
    "shop_id" TEXT NOT NULL DEFAULT '',
    -- 明细类型：co=退单（exceptiondetail/getexceptionco）、present=赠单
    -- （getexceptionpresent）。两个接口的返回结构一样（账单 + children 明细），
    -- 赠单没有阶段概念，co_status 恒为 0。
    "kind" TEXT NOT NULL DEFAULT 'co',
    -- 商龙账单 ID（getexceptionco 返回的 bsId）。整单替换的去重键。
    "bs_id" BIGINT NOT NULL,
    -- 商龙单号，如 YY001301-261113-0162；其中 6 位是营业日。
    "bs_code" TEXT NOT NULL DEFAULT '',
    -- 账单 children 里的行序（0 起）。同一菜品同一时刻可能有两条完全相同的真实
    -- 退菜操作，靠行序而不是字段组合保证它们都留得下来。
    "source_line" INTEGER NOT NULL DEFAULT 0,
    -- 桌台名（如「10」「加3」）。接口没有 table_number，只能存 POS 的桌台名。
    "point_name" TEXT NOT NULL DEFAULT '',
    "item_name" TEXT NOT NULL,
    -- 退菜份数与金额，都取接口原值（正数）。
    "qty" NUMERIC(12, 2) NOT NULL DEFAULT 0,
    "money" NUMERIC(12, 2) NOT NULL DEFAULT 0,
    -- 退单原因（如「客人误点/多点[退菜]」）与操作人。
    "reason" TEXT NOT NULL DEFAULT '',
    "operator" TEXT NOT NULL DEFAULT '',
    "auth_emp" TEXT NOT NULL DEFAULT '',
    -- 营业日 YYYY-MM-DD（取 bs_code 里的日期，跨零点的退菜归前一个营业日）。
    "refund_date" TEXT NOT NULL,
    -- 退菜完整时刻（营业日 + children.time，CHINA_TZ ISO 字符串）。
    "refund_time" TEXT NOT NULL,
    -- 1=预结后退单 2=传菜后退菜 3=结算后退单 4=返位后退单 0=未分类。
    -- 接口不返回该值，同步侧按 coStatus 单独查一遍反推（见 refund_tracker.py）。
    "co_status" INTEGER NOT NULL DEFAULT 0,
    -- 账单时间与结算人，跟明细一起冗余，明细表不用再查一次。
    "settle_time" TEXT NOT NULL DEFAULT '',
    "open_time" TEXT NOT NULL DEFAULT '',
    "settle_man" TEXT NOT NULL DEFAULT '',
    "synced_at" TEXT NOT NULL
);

-- 整单替换的落点：同一账单的明细必须先被删净再插入。kind 必须进唯一键——
-- 同一张账单可能既退菜又赠菜，两个接口各返回一批 children，行序都从 0 开始。
CREATE UNIQUE INDEX IF NOT EXISTS "idx_refund_records_bill_line"
    ON "refund_records" ("tenant_id", "shop_id", "kind", "bs_id", "source_line");

-- 报表按营业日区间筛 + 按退菜时刻倒序。
CREATE INDEX IF NOT EXISTS "idx_refund_records_date"
    ON "refund_records" ("tenant_id", "kind", "refund_date", "refund_time" DESC);
