-- 0030_prep_plan_rebuild.sql
--
-- 备货计划重建（ADR 0117）：页面、接口、计划表一起换。
--
-- 旧模型是三张快照表（`prep_plan_runs` / `prep_plan_items` / `prep_plan_item_slots`）
-- 加一张歇业日日历（`prep_closed_days`）。它们只服务「点一次刷新、落一份 24 小时计划」
-- 那套用法 —— 生产库上线五个月真实用过两次（2026-08-30、08-31），此后无人打开。
-- 新模型是「今天这一张清单」：一天一行（`prep_plan_days`）+ 一行一个品
-- （`prep_plan_entries`），存建议量、店长改后的量、是否已勾。
--
-- ⚠️ **这又是一条非加成性迁移**（0024 之后第二条例外，README 里有记录）。
-- 被删的四张表里，`prep_plan_*` 那 23 条记录是 2026-04-27 / 08-30 / 08-31 的测试性质
-- 数据（其中 1–21 号还是同一时间戳的重复插入），`prep_closed_days` 一条都没有。
-- 删除不构成业务损失；要留档就先跑一次整库备份（管理后台「备份中心 → 导出备份」）。
--
-- 幂等：全部带 IF EXISTS / IF NOT EXISTS，可重复执行。新代码只读新表，
-- 旧表在不在都不影响可用性 —— 所以「先跑迁移」还是「先切代码」都不卡发布。

-- 1) 旧计划表与歇业日日历退场
DROP TABLE IF EXISTS "prep_plan_item_slots";
DROP TABLE IF EXISTS "prep_plan_items";
DROP TABLE IF EXISTS "prep_plan_runs";
DROP TABLE IF EXISTS "prep_closed_days";

-- 2) 备货品归属：厨房做的 / 要买的（先按 category 猜，人在页面上改）
ALTER TABLE "prep_items" ADD COLUMN IF NOT EXISTS "kind" TEXT NOT NULL DEFAULT 'made';
UPDATE "prep_items" SET "kind" = 'bought'
 WHERE "category" = '原料' AND "kind" = 'made';

-- 3) 当日计划：一天一行
CREATE TABLE IF NOT EXISTS "prep_plan_days" (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "plan_day" TEXT NOT NULL,
    "window_start" TEXT NOT NULL,
    "window_end" TEXT NOT NULL,
    "created_at" TEXT NOT NULL,
    "updated_at" TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "idx_prep_plan_days_day"
    ON "prep_plan_days" ("tenant_id", "plan_day");

-- 4) 当日计划明细：一行一个备货品
--
-- `suggested_qty` 每次打开页面按「当前时刻 → 打烊」重算；`final_qty` 是店长改后的数
-- （`qty_source = 'manual'` 的不会被重算覆盖）；`done_at` 是勾选时刻，勾了就不出现在待办里。
CREATE TABLE IF NOT EXISTS "prep_plan_entries" (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "plan_day_id" BIGINT NOT NULL,
    "prep_item_id" BIGINT,
    "item_name" TEXT NOT NULL,
    "unit" TEXT NOT NULL DEFAULT '',
    "station" TEXT NOT NULL DEFAULT '',
    "kind" TEXT NOT NULL DEFAULT 'made',
    "suggested_qty" DOUBLE PRECISION NOT NULL DEFAULT 0,
    "final_qty" DOUBLE PRECISION NOT NULL DEFAULT 0,
    "qty_source" TEXT NOT NULL DEFAULT 'suggested',
    "done_at" TEXT,
    "done_by" TEXT NOT NULL DEFAULT '',
    "basis_json" TEXT,
    "created_at" TEXT NOT NULL,
    "updated_at" TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "idx_prep_plan_entries_day_item"
    ON "prep_plan_entries" ("plan_day_id", "prep_item_id");
CREATE INDEX IF NOT EXISTS "idx_prep_plan_entries_day"
    ON "prep_plan_entries" ("plan_day_id");

-- 5) 员工当日在哪个档口（只看得到自己那一档）
CREATE TABLE IF NOT EXISTS "prep_staff_station_picks" (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "employee_id" BIGINT NOT NULL,
    "pick_day" TEXT NOT NULL,
    "station" TEXT NOT NULL,
    "created_at" TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "idx_prep_staff_station_picks_day"
    ON "prep_staff_station_picks" ("tenant_id", "employee_id", "pick_day");
