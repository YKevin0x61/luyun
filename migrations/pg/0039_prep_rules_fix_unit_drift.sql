-- 0039_prep_rules_fix_unit_drift.sql
--
-- 数据修正（**非加成性**，与 0030 / 0036 同类，需要单独说明）：虾饺的配方系数单位
-- 写的是「份」，备货品主数据是「个」。
--
-- 为什么必须修：备货建议量按 `(semi_name, unit)` 配对规则与备货品。主菜「金牌禄运虾饺皇」
-- 的三条规则（堂食 / 外卖 / 外卖1只）单位都是「份」，卖出去的 9,884 份量全挂在
-- `虾饺(份)` 这一格上，而清单里读的是 `虾饺(个)` —— 两格对不上，参考值恒为 0。
-- 店长 2026-10-27 确认口径：一份虾饺皇用 3 个虾饺，所以同时把系数 1 → 3。
--
-- 只动这三条：`semi_name = '虾饺' AND unit = '份'`。重复执行无行可更（幂等）。
-- 黄网皮（规则「条」/ 主数据「包」）口径未定，**不在本迁移里**，留给核对清单。

UPDATE semi_finished_rules
   SET unit = '个',
       factor = factor * 3
 WHERE semi_name = '虾饺'
   AND unit = '份';
