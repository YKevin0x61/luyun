-- 0029：日常损耗登记（登记台账 / 现场照片 / 常用模板）
--
-- 背景：厨房每天都有报废的食材 —— 变质的、过期的、掉地上摔了的、做废了的、备多了
-- 用不掉的。此前这些事只在群里说一句或纸上写一笔，月底想问「这个月损耗了几次、
-- 什么原因最多、哪几样最费」是答不上来的。这三张表就是那本台账。
--
-- 来源：把它从 worktool2 那个微信小程序搬过来（源项目 `pages/wastage/{add,stats,list}`
-- 三页 + 云函数 `manageWastage` 的两张集合 `wastage_records` / `wastage_templates`）。
-- 搬过来时**口径照旧、形状按本仓库重排**：
--
--   · 一条记录 = 一样物料 + 一个数量与单位 + 一个原因 + 一个**自然日**。
--     `quantity` 是 NUMERIC(12,3) 而不是整数：损耗按 kg / g / 斤 记，0.5 kg 是常见
--     的一笔（源项目里它就是浮点数）。不折成最小单位存，是因为单位本身也要显示
--     （`unit` 是记录的一部分，不是换算系数）。
--   · `reason` 存**英文键**、中文标签在代码里（`services/wastage/store.py` 的
--     `REASONS`）：它是数据面契约，中文名要改的时候不该动历史行。源项目同样把
--     `reason` 与 `reasonText` 都写进去了，这里**只留键**——写两份就一定会漂
--     （改了一处、另一处还是旧的），文案在读取时派生。
--   · `wastage_date` 是 TEXT 的 `YYYY-MM-DD`（同 `staff_assignments.business_date`
--     与 `overtime_entries.entry_date` 的仓库口径）。它是**自然日**，不是 06:00 切的
--     营业日：「今天报废的」这句话里那一天就是日历上的那一天。
--   · `operator_kind` / `employee_id` / `operator_name` 三个字段一起回答「谁登记的」：
--     员工端登记写员工号（`employee_id` 非空），管理端那台共享账号没有员工号、
--     只留 `operator_kind='admin'` —— 同 `overtime_entries.created_by` 的
--     `super` / `staff:<员工号>` 那条口径，只是这里拆成三列，好让「员工只看自己的」
--     直接按 `employee_id` 过滤，不必去解析字符串。
--
-- 照片为什么是第二张表、而不是记录上的一个 JSON 数组：字节在磁盘上（`FileCaptureStore`，
-- 与卫生的照片同一套落盘管线），库里只存引用与元数据。上传与登记是**两步**（先传图拿
-- id、再带 id 提交），所以 `record_id` 允许为空 —— 那就是「传了图但没提交成功」的孤儿行，
-- 留着可查、可清（不做定时清理：源项目也没有，见 `services/wastage/store.py` 的说明）。
--
-- 模板表：`owner_key` 是归属键（`staff:<员工号>` / `super`），**一张表装两种身份的模板**
-- —— 员工存自己的常用组合，管理端存店里的。唯一键把「同一人同一组合」挡在库这一层，
-- 源项目是在云函数里 count 一次再插，并发下会重复。
--
-- 幂等：IF NOT EXISTS，可重复执行。三张表都是**新表**（加成性变更），既有代码与既有
-- 查询在应用前后一个字都不变。

CREATE TABLE IF NOT EXISTS wastage_records (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "item_name" TEXT NOT NULL,
    "quantity" NUMERIC(12, 3) NOT NULL,
    "unit" TEXT NOT NULL,
    "reason" TEXT NOT NULL,
    "remark" TEXT NOT NULL DEFAULT '',
    "wastage_date" TEXT NOT NULL,
    "operator_kind" TEXT NOT NULL,
    "employee_id" BIGINT,
    "operator_name" TEXT NOT NULL,
    "created_at" TEXT NOT NULL,
    "updated_at" TEXT NOT NULL,
    -- 数量必须大于 0：0 与负数不是「一笔损耗」，是白登一笔（同 `overtime_entries` 的
    -- `half_hours <> 0`）。上限 99999 是防手滑多打几个 9，不替业务定政策。
    CONSTRAINT wastage_records_quantity_positive CHECK ("quantity" > 0),
    -- 原因只认那六个键（关键词是 `REASONS`）。放库这一层是为了让「统计里冒出一个
    -- 谁也不认识的原因」不可能发生——绕过接口直接写库也会被拒。
    CONSTRAINT wastage_records_reason_known CHECK (
        "reason" IN ('spoiled', 'expired', 'damaged', 'production_fail', 'excess', 'other')
    ),
    -- 登记人要么是员工（有员工号）、要么是管理端（没有员工号），不能两者都不是。
    CONSTRAINT wastage_records_operator_known CHECK (
        ("operator_kind" = 'staff' AND "employee_id" IS NOT NULL)
        OR ("operator_kind" = 'admin' AND "employee_id" IS NULL)
    )
);

-- 三条访问路径，索引一条对一条：明细与统计按月 / 按日筛（前导列 `wastage_date`）、
-- 员工端读「我自己的」（按人按日期）、原因分布与筛选按原因。前导列不带 `tenant_id`
-- 的理由同 0005/0021（单店阶段代码里没有租户条件）。
CREATE INDEX IF NOT EXISTS idx_wastage_records_date
    ON wastage_records (wastage_date);

CREATE INDEX IF NOT EXISTS idx_wastage_records_employee
    ON wastage_records (employee_id, wastage_date);

CREATE INDEX IF NOT EXISTS idx_wastage_records_reason
    ON wastage_records (reason, wastage_date);

-- 现场照片：`capture_id` 是 `FileCaptureStore` 给的文件名（32 位十六进制），
-- `record_id` 为空 = 上传了但还没绑上任何一条登记。`content_type` 与 `byte_size`
-- 在上传那一刻按**字节内容**识别后落库（不信客户端的 Content-Type，同
-- `services/hygiene/images.py` 的 `sniff_image_content_type`）。
CREATE TABLE IF NOT EXISTS wastage_images (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "record_id" BIGINT REFERENCES wastage_records(id) ON DELETE CASCADE,
    "capture_id" TEXT NOT NULL,
    "owner_key" TEXT NOT NULL,
    "content_type" TEXT NOT NULL,
    "byte_size" BIGINT NOT NULL,
    "sort_order" BIGINT NOT NULL DEFAULT 0,
    "created_at" TEXT NOT NULL,
    -- 同一个 capture 只能被引用一次：重复贴同一张图是前端 bug，不该在库里留两份引用。
    UNIQUE ("tenant_id", "capture_id")
);

-- 读一条登记的图（按记录取，按上传顺序排）与「这个人上传过哪些图」（越权读图的判据）。
CREATE INDEX IF NOT EXISTS idx_wastage_images_record
    ON wastage_images (record_id, sort_order);

CREATE INDEX IF NOT EXISTS idx_wastage_images_owner
    ON wastage_images (owner_key, created_at);

-- 常用模板：同一归属下「物料 + 单位 + 原因」只有一条。源项目在云函数里先 count
-- 再插，并发下会重复；这里把这条规矩交给唯一键。
CREATE TABLE IF NOT EXISTS wastage_templates (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "owner_key" TEXT NOT NULL,
    "owner_kind" TEXT NOT NULL,
    "employee_id" BIGINT,
    "item_name" TEXT NOT NULL,
    "unit" TEXT NOT NULL,
    "reason" TEXT NOT NULL,
    "created_at" TEXT NOT NULL,
    UNIQUE ("tenant_id", "owner_key", "item_name", "unit", "reason"),
    CONSTRAINT wastage_templates_reason_known CHECK (
        "reason" IN ('spoiled', 'expired', 'damaged', 'production_fail', 'excess', 'other')
    )
);

-- 模板列表按归属取（一人一批），建模板时数的也是这一批（上限 20 条，在服务层）。
CREATE INDEX IF NOT EXISTS idx_wastage_templates_owner
    ON wastage_templates (owner_key, created_at);
