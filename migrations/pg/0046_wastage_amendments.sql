-- 0046：损耗登记的更正 —— 24 小时内本人可修改 / 撤回，每次更正留一条 revision
--
-- 背景：0029 把损耗记成「当时发生了什么」的一笔事实，并写明发现写错了就再记一笔说明。
-- 真用起来之后，最常见的错不是「事后改主意」，而是**当场手滑**：数量多打一位、原因点
-- 错一格、备注漏写。再记一笔说明并不能消掉那一笔错的 —— 统计里两笔都在，看报表的人
-- 反而要自己把错的那笔减掉。所以给登记人一个**有边界的**更正口：24 小时内可以改字段、
-- 也可以整笔撤回（软删），窗口外照旧只能另记一笔。
--
-- 为什么窗口是 24 小时、且从 `created_at` 算（不是 `wastage_date`）：
--   · 24 小时够覆盖「当场发现」「下班前核对」「第二天复盘时发现」这三种真实场景；
--     再长就会改到已经被统计页、周报看过的数字，别人看到的数会无解释地变。
--   · 窗口该从**登记那一刻**算，不是从损耗发生日算：`wastage_date` 可以补登前几天
--     的事（0029 允许），按它算等于给补登开了个永远更长的窗口。
--
-- 为什么撤回是软删（`revoked_at`）而不是 DELETE：记录是统计与模板的输入，物理删掉
-- 之后「昨天那个数字怎么变了」就再也查不出来；照片通过 `ON DELETE CASCADE` 外键挂在
-- 记录上，物理删还会连带丢图。软删让所有读路径加一个 `revoked_at IS NULL` 就够，
-- 写入路径仍然只有一个 INSERT（见 `services/wastage/store.py` 的 `_scope_clause`）。
--
-- 为什么单独一张 revision 表、快照存整行 JSON：更正必须留痕（谁、什么时候、改前改后
-- 分别是什么）。存整行 JSON 快照而不是逐列 before/after，是因为记录字段以后还会加，
-- 而修订记录不该被后来的列变更打断（历史行的 JSON 里没有新列是正常的，不会变成
-- 「NULL 表示没改」的歧义）。快照**不含照片**：照片不可换，它不是更正的字段。
--
-- 幂等：只做加成性变更 —— 三列 `ADD COLUMN IF NOT EXISTS`、新表与索引
-- `IF NOT EXISTS`，重复执行不报错。存量读写的行为在应用前后不变（新列都可空）。

ALTER TABLE wastage_records
    ADD COLUMN IF NOT EXISTS "revoked_at" TEXT,
    ADD COLUMN IF NOT EXISTS "revoked_by_kind" TEXT,
    ADD COLUMN IF NOT EXISTS "revoked_by_employee_id" BIGINT;

-- 撤回留操作人（与登记人的三列同一口径）：员工撤回记员工号，管理端撤回没有员工号。
-- 不设 CHECK / 外键：撤回是记录上的一个时间戳，历史行不会被这次变更改写。

CREATE TABLE IF NOT EXISTS wastage_record_revisions (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "record_id" BIGINT NOT NULL REFERENCES wastage_records(id) ON DELETE CASCADE,
    -- 这次更正做了什么：改字段还是整笔撤回。只有这两种，写死在库里。
    "action" TEXT NOT NULL CHECK ("action" IN ('edit', 'revoke')),
    "operator_kind" TEXT NOT NULL,
    "employee_id" BIGINT,
    "operator_name" TEXT NOT NULL,
    -- 改前 / 改后的整行快照（JSON 文本，不含照片）。撤回的 after 是空对象。
    "before_json" TEXT NOT NULL,
    "after_json" TEXT NOT NULL,
    "created_at" TEXT NOT NULL
);

-- 一条记录的全部修订按时间读（详情页展开「改过几次」）；前导列是 record_id。
CREATE INDEX IF NOT EXISTS idx_wastage_revisions_record
    ON wastage_record_revisions (record_id, created_at);
