-- 员工离职（取代「停用」）：带日期的离职状态
--
-- 2026-10-29 用户裁定：花名册的「停用」改成「离职」，登记离职必须带日期（允许将来，
-- 与入职日期同一条口径——提前登记「干到月底」）。一列表示三种态：
--
--   NULL          = 在职（还没离职）
--   ''            = 已离职、日期待补（存量从 `disabled = 1` 迁过来的那些人）
--   'YYYY-MM-DD'  = 已离职，自该日起不再算在职（**当天仍然上班**，判据是「今天 < 离职日」）
--
-- 为什么一列而不是「布尔 + 日期」两列：两个字段会打架（布尔为真、日期却空），而这里
-- 每个判据都只问一个问题——「到今天为止他还在不在」。空串是唯一一个特例：
-- 「已经走了，但哪天走的没人记得」，它让「必填」有且只有一个例外，且这个例外看得见
-- （花名册上标「离职日期待补」）。
--
-- `disabled` 列**保留但不读不写**：迁移只做加成性变更（migrations/pg/README.md），
-- 删列走不了。它上面的存量在这一条里迁完，之后不再有新写入。

ALTER TABLE hygiene_employees ADD COLUMN IF NOT EXISTS "resigned_at" TEXT;

-- 存量：已停用的人迁成「已离职、日期待补」。幂等：已经迁过的行（`resigned_at` 非空）
-- 不会因为再跑一次而被改掉。
UPDATE hygiene_employees
   SET resigned_at = ''
 WHERE disabled <> 0
   AND resigned_at IS NULL;
