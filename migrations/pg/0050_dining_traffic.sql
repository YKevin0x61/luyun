-- 0047_dining_traffic.sql
--
-- 客流 / 翻台按小时一行（票 10 / `.scratch/prep-review/spec.md` §12 的 P2）。
--
-- 为什么要有这张表：复盘现在能回答「那天够不够卖」，但回答不了「为什么」。
-- 客流（在座人数）与翻台（开台数 / 总桌数）是解释备货偏离最便宜的现场信号 ——
-- 中午满座却卖不动，是备多了；空场却售罄，是备少了。桌台快照（`tables`）是
-- **覆盖式**的「此刻状态」，每轮采集 DELETE + INSERT，历史留不下来，所以另开一张
-- 「一小时一行」的汇总表。
--
-- 形状的取舍：
--   · 只存**按小时汇总**的三个数，不存每张桌的行 —— 复盘按天 × 钟点看曲线，
--     一天最多 24 行；存明细会让这张表按采集频率（分钟级）膨胀，且没有消费方。
--   · `snapshot_at` 是**截断到整点**的 ISO8601 文本（仓库时间列一律 TEXT，
--     见 README「已知取舍」），`UNIQUE (tenant_id, snapshot_at)` 让「同一小时只留
--     一行」由库保证；写入走 `ON CONFLICT ... DO UPDATE` 刷新数值。
--   · `plan_day` 是自然日 `YYYY-MM-DD`（与 `prep_plan_days` / `prep_plan_events`
--     同口径），冗余存一份是为了按天翻页不用对 `snapshot_at` 做函数运算。
--   · `id` 是代理主键：通用后台表格页按 `rowid`（方言层改写为 `id`）定位行，
--     缺 id 会让 `/api/admin/tables/dining_traffic/rows` 500，行编辑/删除一起坏。
--
-- 幂等：建表 / 建索引全部 `IF NOT EXISTS`，可重复执行。纯加成性变更：不动既有表。
-- schema 不随启动生效，需在 Admin「系统更新 → 数据库迁移」或更新作业的
-- `applying_migrations` 阶段应用（见 `migrations/pg/README.md`）。

CREATE TABLE IF NOT EXISTS "dining_traffic" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "tenant_id" BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    -- 截断到整点、带 +08:00 偏移的 ISO8601 文本。
    "snapshot_at" TEXT NOT NULL,
    -- 自然日 YYYY-MM-DD。
    "plan_day" TEXT NOT NULL,
    -- 在座人数：桌台快照里各行人数之和。
    "in_seat_people" BIGINT NOT NULL DEFAULT 0,
    -- 开台数：有客（人数或金额大于 0）的桌数。
    "open_tables" BIGINT NOT NULL DEFAULT 0,
    -- 总桌数：本轮快照的行数。
    "total_tables" BIGINT NOT NULL DEFAULT 0,
    "created_at" TEXT NOT NULL,
    -- 「同一小时一行」由库保证；写入按 (tenant_id, snapshot_at) upsert。
    UNIQUE ("tenant_id", "snapshot_at")
);

-- 复盘页按「某天 → 时间顺序」读一天的小时曲线。
CREATE INDEX IF NOT EXISTS "idx_dining_traffic_day_hour"
    ON "dining_traffic" ("plan_day", "snapshot_at");
