-- 0053_staff_meal.sql
--
-- 员工餐采购计划（ADR 0135，`.scratch/staff-meal/spec.md`）：月度 Excel 菜单 → 每日采购单
-- → 汇总推送企微核心群。四张表，全部新增、纯加成性，可重复执行。
--
-- 模型：
--
--   `staff_meal_menu_days`   一天一行：当月每天的午/晚餐菜品（主菜 + 两道副菜）、饮品/水果，
--                            `freeform` 标记「自主发挥」日（菜单当天不排、现场定）。
--                            一个自然月 = 该月每一天一行，没有的日期就是没导过菜单。
--   `staff_meal_orders`      一天一张采购单：`draft` 是导入时自动建的空单，`submitted` 是
--                            已提交并推送过的单。`push_seq` 每次提交/重推 +1，拼进企微出站的
--                            `business_reference`，保证「改完重推」不会被幂等去重吞掉。
--   `staff_meal_order_dishes` 单内菜品：导入建单时从菜单**物化**下来，是快照 —— 之后重传
--                            菜单只刷新草稿单的菜，已提交单保持提交时的样子。
--   `staff_meal_order_items`  采购条目：`dish_id` 非空 = 该菜要买的食材；为空 = 单据级
--                            「其他采购项」（菜单外调料/杂物、自主发挥日现场买的菜）。
--                            同名菜复用只带出 `item_name`，`quantity` 留空（用户裁定）。
--
-- 日期一律 TEXT（`YYYY-MM-DD`，项目口径），时刻列是 CHINA_TZ 的 ISO 字符串。
-- 数量允许空（只带出食材名时）；单位是自由文本（常用项当前端快捷候选，不是白名单）。
--
-- 应用方式见 `migrations/pg/README.md`：更新作业的 `applying_migrations` 阶段或 Admin
-- 「系统更新 → 数据库迁移」。schema 不随应用重启生效。

CREATE TABLE IF NOT EXISTS "staff_meal_menu_days" (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "menu_date" TEXT NOT NULL,
    "weekday" INTEGER,
    "lunch_main" TEXT,
    "lunch_side1" TEXT,
    "lunch_side2" TEXT,
    "dinner_main" TEXT,
    "dinner_side1" TEXT,
    "dinner_side2" TEXT,
    "drink" TEXT,
    "freeform" BOOLEAN NOT NULL DEFAULT FALSE,
    "source" TEXT NOT NULL DEFAULT 'xlsx',
    "created_at" TEXT NOT NULL,
    "updated_at" TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "idx_staff_meal_menu_days_date"
    ON "staff_meal_menu_days" ("tenant_id", "menu_date");

CREATE TABLE IF NOT EXISTS "staff_meal_orders" (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "order_date" TEXT NOT NULL,
    "status" TEXT NOT NULL DEFAULT 'draft',
    "remark" TEXT,
    "submitter_employee_id" BIGINT,
    "submitter_name" TEXT,
    "submitted_at" TEXT,
    "push_status" TEXT NOT NULL DEFAULT 'not_pushed',
    "pushed_at" TEXT,
    "push_error" TEXT,
    "push_seq" INTEGER NOT NULL DEFAULT 0,
    "created_at" TEXT NOT NULL,
    "updated_at" TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "idx_staff_meal_orders_date"
    ON "staff_meal_orders" ("tenant_id", "order_date");
CREATE INDEX IF NOT EXISTS "idx_staff_meal_orders_status"
    ON "staff_meal_orders" ("tenant_id", "status", "push_status");

CREATE TABLE IF NOT EXISTS "staff_meal_order_dishes" (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "order_id" BIGINT NOT NULL REFERENCES "staff_meal_orders"("id") ON DELETE CASCADE,
    "dish_name" TEXT NOT NULL,
    "meal" TEXT NOT NULL,
    "role" TEXT,
    "sort_order" INTEGER NOT NULL DEFAULT 0,
    "created_at" TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS "idx_staff_meal_order_dishes_order"
    ON "staff_meal_order_dishes" ("order_id");

CREATE TABLE IF NOT EXISTS "staff_meal_order_items" (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "order_id" BIGINT NOT NULL REFERENCES "staff_meal_orders"("id") ON DELETE CASCADE,
    "dish_id" BIGINT REFERENCES "staff_meal_order_dishes"("id") ON DELETE CASCADE,
    "item_name" TEXT NOT NULL,
    "quantity" NUMERIC(10,2),
    "unit" TEXT,
    "sort_order" INTEGER NOT NULL DEFAULT 0,
    "created_at" TEXT NOT NULL,
    "updated_at" TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS "idx_staff_meal_order_items_order"
    ON "staff_meal_order_items" ("order_id");
CREATE INDEX IF NOT EXISTS "idx_staff_meal_order_items_name"
    ON "staff_meal_order_items" ("tenant_id", "item_name");
