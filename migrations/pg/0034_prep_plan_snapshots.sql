-- 0034_prep_plan_snapshots.sql
--
-- 参考值每小时快照（ADR 0123）：留存「当时给了多少、凭什么给」，供以后复盘与调公式。
--
-- 为什么必须新建表：`prep_plan_entries` 是「当日计划」，页面每次打开都会重算并 upsert
-- 覆盖，历史留不住；而且它按天一行，没有小时粒度。
--
-- 两张表**刻意分开**：
--   `prep_plan_snapshots`（预测侧）—— 每小时整点写一次，是历史事实，永不重算；
--   `prep_plan_actuals`  （实际侧）—— 窗口结束后回填，随时可以重算（比如改了配方重跑）。
-- 复盘时按 (window_start, window_end, prep_item_id) 对齐两边。
--
-- 两边都存 `rules_fingerprint`（当日 semi_finished_rules 的 md5）：配方一改，历史窗口
-- 按新规则重算出来的「实际销量」与当时的预测就不同源了，复盘页据此标「对比不可靠」。
--
-- 幂等：IF NOT EXISTS，可重复执行。纯加成性变更。

CREATE TABLE IF NOT EXISTS "prep_plan_snapshots" (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "snapshot_at" TEXT NOT NULL,
    "window_start" TEXT NOT NULL,
    "window_end" TEXT NOT NULL,
    "plan_day" TEXT NOT NULL,
    "prep_item_id" BIGINT NOT NULL,
    "item_name" TEXT NOT NULL,
    "unit" TEXT NOT NULL DEFAULT '',
    "station" TEXT NOT NULL DEFAULT '',
    "suggested_qty" DOUBLE PRECISION NOT NULL DEFAULT 0,
    "demand_qty" DOUBLE PRECISION NOT NULL DEFAULT 0,
    "final_qty" DOUBLE PRECISION,
    "qty_source" TEXT NOT NULL DEFAULT 'suggested',
    "store_factor" DOUBLE PRECISION NOT NULL DEFAULT 1,
    "quantile" DOUBLE PRECISION NOT NULL DEFAULT 0.4,
    "basis_json" TEXT NOT NULL DEFAULT '{}',
    "rules_fingerprint" TEXT NOT NULL DEFAULT '',
    "created_at" TEXT NOT NULL,
    UNIQUE ("tenant_id", "snapshot_at", "prep_item_id")
);

CREATE INDEX IF NOT EXISTS "idx_prep_snapshots_day"
    ON "prep_plan_snapshots" ("plan_day", "snapshot_at");

CREATE TABLE IF NOT EXISTS "prep_plan_actuals" (
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "window_start" TEXT NOT NULL,
    "window_end" TEXT NOT NULL,
    "prep_item_id" BIGINT NOT NULL,
    "item_name" TEXT NOT NULL,
    "unit" TEXT NOT NULL DEFAULT '',
    "station" TEXT NOT NULL DEFAULT '',
    "sold_qty" DOUBLE PRECISION NOT NULL DEFAULT 0,
    "rules_fingerprint" TEXT NOT NULL DEFAULT '',
    "computed_at" TEXT NOT NULL,
    UNIQUE ("tenant_id", "window_start", "window_end", "prep_item_id")
);
