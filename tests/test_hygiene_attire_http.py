def test_submit_requires_live_capture(attire_http):
    client, _attire = attire_http
    assert _set_standard(client).status_code == 200

    # 没有 live 标志 = 从相册挑的：这一条要挡住（ADR 0050）。
    refused = client.post(
        STAFF_SUBMIT,
        files={"file": ("album.jpg", _jpeg(), "image/jpeg")},
        data={"live": "false"},
    )
    assert refused.status_code == 400
    assert "现场" in refused.json()["detail"]

    ok = client.post(
        STAFF_SUBMIT,
        files={"file": ("live.jpg", _jpeg(), "image/jpeg")},
        data={"live": "true"},
    )
    assert ok.status_code == 200
    assert ok.json()["attire"]["status"] == "pending"


