"""仪容仪表的 HTTP 契约：鉴权、两步拍照的上传形状、验收动作与人话报错。

服务层细节在 ``test_hygiene_attire.py``；这里只钉端点行为 —— 尤其是这三条：

- **鉴权**：员工侧要员工会话、管理侧要管理员会话；`_get_attire` 没配好时不能因为
  ``from main import`` 把整个应用拉起来（这里一律 override 掉，跟其它卫生端点的测法一致）。
- **两步拍照**：员工交的那张必须带 ``live=true``（ADR 0050），标准图**不**带也行 ——
  两者在同一个路由模块里，边界要钉住。
- **人话报错**：驳回不写原因、图没交就想验收、还没传标准图，回来的都是中文文案，
  不是内部错误码。
"""

