ADMIN_STANDARD = "/api/hygiene/admin/attire/standard"
ADMIN_DATA_EXPORT = "/api/hygiene/admin/data/export/jobs"


def _run(coro):
    try:
        loop = asyncio.get_event_loop()
    except RuntimeError:
        loop = asyncio.new_event_loop()
        asyncio.set_event_loop(loop)
    return loop.run_until_complete(coro)


def _jpeg(color=(30, 90, 120)) -> bytes:
    output = io.BytesIO()
    Image.new("RGB", (120, 90), color).save(output, format="JPEG", quality=90)
    return output.getvalue()


def _build(tmp_path):
    settings.DATABASE_DIR = str(tmp_path)
    db = DatabaseManager()
    _run(db.connect())
    work = HygieneWork(
        db,
        captures=FileCaptureStore(Path(tmp_path) / "hygiene-captures"),
        now=lambda: NOW,
        image_variants=ImageVariantGenerator(),
    )
    _run(work.prepare())
    attire = HygieneAttire(work, now=lambda: NOW)

    now_iso = NOW.isoformat()
    for employee_id, phone, name in ((ZHANGSAN, DAY_PHONE, "张三"), (LISI, "13800000002", "李四")):
        _run(
            db._conn.execute(
                """INSERT INTO hygiene_employees
                       (id, phone, name, password_hash, permission, approved,
                        created_at, updated_at)
                   VALUES (?, ?, ?, '', '普通员工', 1, ?, ?)""",
                (employee_id, phone, name, now_iso, now_iso),
            )
        )
    # 排班结果行直接铺：attire 的判据就是「那天有没有班次」，它读结果、不读规则。
    #
    # 这里**不走 `SchedulingStore`**：铺规则的入口读的是全局 runtime 里的那个库
    # （`set_runtime` 的实例会被别的用例覆盖），而 HTTP 这一层根本不需要它。
    _run(
        db._conn.execute(
            """INSERT INTO staff_shifts
                   (id, name, sort_order, is_active, created_at, updated_at)
               VALUES (?, '白班', 0, 1, ?, ?)""",
            (SHIFT_ID, now_iso, now_iso),
        )
    )
    _run(
        db._conn.execute(
            """INSERT INTO staff_assignments
                   (employee_id, business_date, shift_id, zone_id, source,
                    created_at, updated_at)
               VALUES (?, ?, ?, NULL, 'manual', ?, ?)""",
            (ZHANGSAN, business_date_of(NOW), SHIFT_ID, now_iso, now_iso),
        )
    )
    # 李四一行都不铺：今天没排到他 —— 员工侧整行不显示，交活也要被拒。
    _run(db._conn.commit())
    return db, work, attire


def _make_app(work, attire, db, *, staff_id=ZHANGSAN, admin=True):
    app = FastAPI()
    app.include_router(hygiene_module.router)
    # `_get_work` / `_get_attire` / `_get_accounts` 都是 `from main import …` 的取值口，
    # 不 override 就会把整个应用（连同 lifespan）拖进测试。
    app.dependency_overrides[hygiene_module._get_work] = lambda: work
    app.dependency_overrides[hygiene_module._get_attire] = lambda: attire
    # 账号走**真实**那一个（没登录时 `get_staff_session(None)` 返回 None → 401）：
    # 「未登录」这条用例要测的就是真鉴权路径，不能把依赖换成一句写死的 401。
    app.dependency_overrides[hygiene_module._get_accounts] = lambda: EmployeeAccounts(db)
    # 归档也是同一个取值口（`from main import hygiene_archive`）：导出那两条路由要用它，
    # 不 override 就是 500 —— 现有 data 那套 HTTP 测试也是这么接的。
    app.dependency_overrides[hygiene_module._get_archive] = lambda: HygieneDataArchive(
        db, work._captures
    )
    if admin:
        app.dependency_overrides[hygiene_module.require_session] = lambda: "test-admin"
    if staff_id is not None:
        app.dependency_overrides[hygiene_module.require_staff_session] = lambda: {
            "session_id": "test-staff",
            "employee": {"id": staff_id, "name": "张三", "phone": DAY_PHONE},
        }
    return app


